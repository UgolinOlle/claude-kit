import type { PackCommand, StackPack } from "./types.ts";

const RUN: Record<string, string> = { bun: "bun run", pnpm: "pnpm", yarn: "yarn", npm: "npm run" };

/** Scripts worth surfacing, in display order. */
const SCRIPT_ORDER = ["dev", "start", "build", "test", "test:unit", "test:e2e", "lint", "typecheck", "type-check", "check", "format"];

const LOCKFILE_REASON = "lockfiles are generated by the package manager; change package.json and reinstall instead";

export const nodePack: StackPack = {
  id: "node",

  label(stack) {
    const ts = stack.node?.typescript;
    const runtime = stack.manager === "bun" ? "Bun" : "Node.js";
    return `${ts ? "TypeScript" : "JavaScript"} on ${runtime}`;
  },

  ignore: [
    "node_modules/",
    "dist/",
    "build/",
    "out/",
    ".next/",
    ".nuxt/",
    ".svelte-kit/",
    ".turbo/",
    ".nx/",
    ".cache/",
    ".parcel-cache/",
    "coverage/",
    "storybook-static/",
    "*.min.js",
    "*.map",
    "*.tsbuildinfo",
    "package-lock.json",
    "pnpm-lock.yaml",
    "yarn.lock",
    "bun.lock",
    "bun.lockb",
  ],

  protectedPaths: [
    { pattern: "package-lock.json", reason: LOCKFILE_REASON },
    { pattern: "pnpm-lock.yaml", reason: LOCKFILE_REASON },
    { pattern: "yarn.lock", reason: LOCKFILE_REASON },
    { pattern: "bun.lock", reason: LOCKFILE_REASON },
    { pattern: "bun.lockb", reason: LOCKFILE_REASON },
    { pattern: "node_modules/", reason: "dependencies are installed, not edited; patch via the package manager" },
    { pattern: "dist/", reason: "build output is generated; edit the sources instead" },
  ],

  commands(stack) {
    const run = RUN[stack.manager] ?? "npm run";
    const scripts = stack.node?.scripts ?? {};
    const out: PackCommand[] = [{ label: "install", cmd: `${stack.manager} install` }];
    for (const name of SCRIPT_ORDER) {
      if (!scripts[name]) continue;
      // `bun test` is the built-in runner and differs from `bun run test`; keep the script's intent.
      out.push({ label: name, cmd: `${run} ${name}` });
    }
    if (!scripts.test && stack.manager === "bun") out.push({ label: "test", cmd: "bun test" });
    return out;
  },
};

